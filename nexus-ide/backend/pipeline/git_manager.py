"""GitManager — automatic version control for generated projects.

Handles git init, feature branches, conventional commits, and
semantic tagging with LLM-generated commit messages.
"""
from __future__ import annotations

import logging
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from backend.config.settings import get_settings
from backend.tools.ollama_client import OllamaClient

logger = logging.getLogger(__name__)


@dataclass
class ConventionalCommit:
    """Parsed conventional commit."""

    type_: str  # feat, fix, docs, refactor, test, chore
    scope: str
    description: str
    body: str = ""
    breaking: bool = False

    def format(self) -> str:
        prefix = f"{self.type_}"
        if self.scope:
            prefix += f"({self.scope})"
        if self.breaking:
            prefix += "!"
        lines = [f"{prefix}: {self.description}"]
        if self.body:
            lines.append("")
            lines.append(self.body)
        return "\n".join(lines)


class GitManager:
    """Automates git operations for AI-generated code."""

    COMMIT_PROMPT = """You are a git commit message generator.
Analyze the following file changes and generate a conventional commit message.

CONVENTIONAL COMMIT FORMAT:
type(scope): description

Types: feat, fix, docs, style, refactor, test, chore
- feat: new feature
- fix: bug fix
- docs: documentation only
- style: formatting, missing semi colons, etc.
- refactor: code change that neither fixes a bug nor adds a feature
- test: adding or correcting tests
- chore: build process or auxiliary tool changes

RULES:
1. Use imperative mood: "Add feature" not "Added feature"
2. Keep description under 72 characters
3. Scope should be the main module or component affected
4. Include story ID in body if provided

OUTPUT FORMAT:
Return ONLY the commit message text, no markdown, no code blocks."""

    def __init__(self, repo_path: Path, ollama_client: OllamaClient | None = None) -> None:
        self.repo_path = Path(repo_path)
        self._client = ollama_client or OllamaClient(get_settings().ollama_host)

    def _run(self, cmd: list[str], check: bool = True) -> subprocess.CompletedProcess[str]:
        """Run a git command in the repository."""
        result = subprocess.run(
            ["git", *cmd],
            cwd=self.repo_path,
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=False,
        )
        if check and result.returncode != 0:
            raise GitError(f"git {' '.join(cmd)} failed: {result.stderr.strip()}")
        return result

    # ------------------------------------------------------------------
    # Repository lifecycle
    # ------------------------------------------------------------------

    def init_repo(self, initial_commit: bool = True) -> None:
        """Initialize a git repository with an initial commit."""
        self.repo_path.mkdir(parents=True, exist_ok=True)
        if not (self.repo_path / ".git").exists():
            self._run(["init"])
            logger.info("Initialized git repo at %s", self.repo_path)

        if initial_commit:
            # Configure git user for automated commits
            self._run(["config", "user.email", "nexus@auto.dev"], check=False)
            self._run(["config", "user.name", "NEXUS Bot"], check=False)

            # Create initial commit with template README
            readme = self.repo_path / "README.md"
            if not readme.exists():
                readme.write_text("# Generated by NEXUS\n\nThis project was auto-generated.\n")
            self._run(["add", "."], check=False)
            self._run(["commit", "-m", "chore: initial commit from NEXUS"], check=False)
            logger.info("Created initial commit")

    # ------------------------------------------------------------------
    # Branching
    # ------------------------------------------------------------------

    def create_feature_branch(self, story_id: str, description: str) -> str:
        """Create a feature branch following naming conventions.

        Args:
            story_id: Unique story identifier (e.g., "story-abc12345").
            description: Short description for the branch name.

        Returns:
            The branch name created.
        """
        # Sanitize description for branch name
        safe_desc = re.sub(r"[^a-zA-Z0-9-]", "-", description.lower())
        safe_desc = re.sub(r"-+", "-", safe_desc).strip("-")
        branch_name = f"feature/{story_id}-{safe_desc[:40]}"

        self._run(["checkout", "-b", branch_name])
        logger.info("Created branch %s", branch_name)
        return branch_name

    def checkout(self, branch: str) -> None:
        """Checkout an existing branch."""
        self._run(["checkout", branch])

    def current_branch(self) -> str:
        """Return the current branch name."""
        result = self._run(["rev-parse", "--abbrev-ref", "HEAD"])
        return result.stdout.strip()

    # ------------------------------------------------------------------
    # Committing
    # ------------------------------------------------------------------

    def stage_all(self) -> None:
        """Stage all changes."""
        self._run(["add", "."])

    def commit(self, message: str, check_empty: bool = True) -> str:
        """Create a commit with the given message.

        Returns:
            The commit hash.
        """
        self._run(["commit", "-m", message], check=not check_empty)
        result = self._run(["rev-parse", "HEAD"])
        return result.stdout.strip()

    def commit_files(
        self,
        files: list[str],
        message: str,
        story_id: str = "",
    ) -> str:
        """Stage specific files and commit them.

        Args:
            files: Relative paths to stage.
            message: Commit message.
            story_id: Optional story ID to include in commit body.

        Returns:
            The commit hash.
        """
        for f in files:
            self._run(["add", f])

        full_message = message
        if story_id:
            full_message += f"\n\nStory: {story_id}"
        full_message += "\n\nGenerated with NEXUS"

        return self.commit(full_message)

    async def generate_commit_message(
        self,
        diff: str,
        story_id: str = "",
    ) -> ConventionalCommit:
        """Generate a conventional commit message from a diff using LLM.

        Args:
            diff: Git diff output.
            story_id: Optional story reference.

        Returns:
            Parsed ConventionalCommit object.
        """
        prompt = f"""File changes:
```diff
{diff[:4000]}
```

{'Story: ' + story_id if story_id else ''}

Generate a conventional commit message."""

        try:
            response = await self._client.chat(
                messages=[
                    {"role": "system", "content": self.COMMIT_PROMPT},
                    {"role": "user", "content": prompt},
                ],
                model="llama3.2",
                temperature=0.3,
            )
            content = response.content if hasattr(response, "content") else str(response)
            return self._parse_commit_message(content.strip())
        except Exception as exc:
            logger.warning("LLM commit generation failed: %s", exc)
            return ConventionalCommit(
                type_="chore",
                scope="auto",
                description="automated update",
                body=f"Story: {story_id}" if story_id else "",
            )

    def _parse_commit_message(self, text: str) -> ConventionalCommit:
        """Parse conventional commit format from text."""
        lines = text.strip().split("\n")
        header = lines[0]

        # Pattern: type(scope): description or type!: description
        match = re.match(
            r"^(\w+)(?:\(([^)]+)\))?(!)?\s*:\s*(.+)$",
            header,
        )
        if match:
            return ConventionalCommit(
                type_=match.group(1),
                scope=match.group(2) or "",
                description=match.group(4),
                body="\n".join(lines[1:]).strip(),
                breaking=match.group(3) is not None,
            )

        # Fallback
        return ConventionalCommit(
            type_="chore",
            scope="auto",
            description=header[:72],
            body="\n".join(lines[1:]).strip(),
        )

    # ------------------------------------------------------------------
    # Tagging
    # ------------------------------------------------------------------

    def tag_release(self, version: str, message: str = "") -> None:
        """Create an annotated tag for a release."""
        tag_msg = message or f"Release {version}"
        self._run(["tag", "-a", version, "-m", tag_msg])
        logger.info("Created tag %s", version)

    # ------------------------------------------------------------------
    # Diff & status
    # ------------------------------------------------------------------

    def diff(self, cached: bool = False) -> str:
        """Return the current diff."""
        cmd = ["diff", "--cached"] if cached else ["diff"]
        result = self._run(cmd, check=False)
        return result.stdout

    def has_uncommitted_changes(self) -> bool:
        """Check if there are uncommitted changes."""
        result = self._run(["status", "--porcelain"], check=False)
        return bool(result.stdout.strip())

    def log_summary(self, n: int = 5) -> list[dict[str, Any]]:
        """Return recent commit history."""
        fmt = "%H|%s|%an|%ad"
        result = self._run(
            ["log", f"--format={fmt}", f"-{n}", "--date=short"],
            check=False,
        )
        commits: list[dict[str, Any]] = []
        for line in result.stdout.strip().split("\n"):
            if "|" in line:
                hash_, subject, author, date = line.split("|", 3)
                commits.append({
                    "hash": hash_,
                    "subject": subject,
                    "author": author,
                    "date": date,
                })
        return commits


class GitError(Exception):
    """Raised when a git operation fails."""
