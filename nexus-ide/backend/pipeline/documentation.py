"""Documentation generators — ADRs, inline comments, READMEs.

Produces human-readable documentation explaining architectural decisions
and code structure.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .architecture import ArchitecturalDecision, DecisionRecorder

logger = logging.getLogger(__name__)


@dataclass
class CodeComment:
    """A generated code comment."""

    file_path: str
    line_number: int
    comment_type: str  # architecture, pattern, security, performance
    text: str


class CommentGenerator:
    """Generates explanatory comments for generated code."""

    PATTERN_COMMENTS: dict[str, str] = {
        "Repository": (
            "# Architecture Decision: Using Repository pattern\n"
            "# Why: Abstracts data access for testability and allows\n"
            "#      swapping storage backends without changing business logic."
        ),
        "Factory": (
            "# Architecture Decision: Using Factory pattern\n"
            "# Why: Centralizes object creation logic and makes it easy\n"
            "#      to extend with new variants without modifying callers."
        ),
        "Observer": (
            "# Architecture Decision: Using Observer pattern\n"
            "# Why: Decouples event producers from consumers, enabling\n"
            "#      independent scaling and testing of components."
        ),
        "Singleton": (
            "# Architecture Decision: Using Singleton pattern\n"
            "# Why: Ensures a single shared instance for global resources.\n"
            "#      Consider dependency injection for better testability."
        ),
    }

    def generate_pattern_comment(self, pattern_name: str) -> str:
        """Get an explanatory comment for a design pattern."""
        return self.PATTERN_COMMENTS.get(
            pattern_name,
            f"# Using {pattern_name} pattern for modularity and maintainability.",
        )

    def generate_architecture_comment(self, template_name: str) -> str:
        """Generate a module-level architecture comment."""
        return (
            f'"""\n'
            f"Module generated with {template_name} architecture.\n\n"
            f"This file follows the project's layered architecture.\n"
            f"See docs/architecture.md for the full rationale.\n"
            f'"""\n'
        )

    def generate_security_comment(self, concern: str) -> str:
        """Generate a security-related comment."""
        comments = {
            "input_validation": (
                "# SECURITY: Always validate and sanitize user input.\n"
                "# Never trust external data — validate type, length, and format."
            ),
            "sql_injection": (
                "# SECURITY: Use parameterized queries to prevent SQL injection.\n"
                "# Never interpolate user input into SQL strings."
            ),
            "secrets": (
                "# SECURITY: Load secrets from environment variables.\n"
                "# Never hardcode credentials or API keys in source code."
            ),
        }
        return comments.get(concern, "# Security consideration applied.")


class ReadmeGenerator:
    """Generates README.md files for projects."""

    TEMPLATE = """# {project_name}

Generated by NEXUS OMEGA on {date}.

## Architecture

{architecture}

## Stack

{stack}

## Setup

```bash
{setup_commands}
```

## Running Tests

```bash
{test_commands}
```

## Project Structure

```
{file_tree}
```

## Architectural Decisions

{adr_summary}

---

*This project was auto-generated. For questions, consult the NEXUS dashboard.*
"""

    def generate(
        self,
        project_name: str,
        stack: str,
        architecture: str,
        setup_commands: str,
        test_commands: str,
        file_tree: str,
        decisions: list[ArchitecturalDecision],
    ) -> str:
        """Generate a README markdown string."""
        from datetime import datetime

        adr_summary = "\n".join(
            f"- **{d.decision_id}**: {d.decision[:100]}..."
            for d in decisions
        ) if decisions else "No major architectural decisions recorded."

        return self.TEMPLATE.format(
            project_name=project_name,
            date=datetime.now().strftime("%Y-%m-%d"),
            architecture=architecture,
            stack=stack,
            setup_commands=setup_commands,
            test_commands=test_commands,
            file_tree=file_tree,
            adr_summary=adr_summary,
        )
