"""The public (unauthenticated) route inventory for deny-by-default auth.

One module, one job: name every route that may answer an anonymous request.
Anything not named here is protected — see
:mod:`backend.middleware.deny_by_default`, which refuses anonymous requests to
every other registered route.

Why an explicit allowlist instead of "protect the risky ones"
------------------------------------------------------------
The opposite policy was measured on this codebase: 386 registered routes, 95 of
them answering without any authentication.  Each of those 95 was a deliberate
decision at some point (a liveness probe, a docs page, a dashboard SSE that
"was only internal"), and every one of them is a hole the day that assumption
stops being true.  An allowlist inverts the default: a new route is protected
the moment it is registered, and making it public is a reviewable change to
this file.

The cost of that inversion is this list must stay truthful, so it is small,
explicit, and each entry says why it exists.
"""

from __future__ import annotations

#: HTTP routes that answer anonymous callers, as ``(method, path_format)``.
#:
#: ``path_format`` is Starlette's route template (``/api/x/{id}``), because the
#: middleware matches the template, not the concrete request path — otherwise
#: every path parameter would need an allowlist entry.
#:
#: Grouped by *why* the route is public, not by router:
PUBLIC_HTTP_ROUTES: frozenset[tuple[str, str]] = frozenset(
    {
        # --- Liveness / readiness -------------------------------------------
        # Container and orchestrator probes cannot carry a bearer token, and a
        # probe that needs credentials reports "unhealthy" during an auth
        # outage.  These carry no internal topology (the deep variants,
        # /api/deep and /health?deep=true, are NOT here — they require auth).
        ("GET", "/health"),
        ("GET", "/api/health"),
        ("GET", "/api/ready"),
        # --- Build identity --------------------------------------------------
        # Version + git sha.  Exposes no secret, and it is the only way to
        # answer "is this the fixed build?" from outside the host.
        ("GET", "/version"),
        ("GET", "/api/version"),
        # --- Prometheus text exposition ---------------------------------------
        # config/prometheus.yml scrapes backend:8000 at the default
        # metrics_path; Prometheus has no auth story by default.
        ("GET", "/metrics"),
        # --- Authentication itself --------------------------------------------
        # Login/register/refresh are how a caller *obtains* the token that
        # every other route requires.  ``/api/auth/me`` and
        # ``/api/auth/logout`` are deliberately absent: they act on an
        # authenticated session.
        #
        # ``/api/auth/register`` stays public even though self-registration
        # is disabled outside development (``allow_self_registration`` in
        # backend/config/settings.py): the route has to be reachable to
        # answer 403 with that reason.  A 401 from the edge would say
        # "you need a token", which is not what is wrong with the request.
        ("POST", "/api/auth/login"),
        ("POST", "/api/auth/register"),
        ("POST", "/api/auth/refresh"),
    }
)

#: Documentation routes that answer anonymous callers, same tuple shape.
#:
#: Kept separate from :data:`PUBLIC_HTTP_ROUTES` because these are generated by
#: FastAPI's own docs app rather than by application code, so a reviewer
#: scanning route files would not find them.  Disabling the docs entirely is a
#: separate decision (``docs_url=None`` / ``openapi_url=None`` at app
# construction); the schema is public by default and this list says so out loud.
PUBLIC_DOCS_ROUTES: frozenset[tuple[str, str]] = frozenset(
    {
        ("GET", "/openapi.json"),
        ("GET", "/docs"),
        ("GET", "/docs/oauth2-redirect"),
        ("GET", "/redoc"),
    }
)

#: WebSocket routes that may complete an anonymous handshake, same tuple shape.
#:
#: Empty on purpose.  Every WebSocket on this app streams internal state
#: (agent thinking feed, mission events), so each one demands a token.  The set
#: exists so that adding a public WebSocket later is a conscious edit here
#: rather than a hole discovered in an audit — and so the contract test can
#: assert the inventory is still covering the app.
PUBLIC_WS_ROUTES: frozenset[tuple[str, str]] = frozenset()


def is_public_http_route(method: str, path_format: str) -> bool:
    """Whether ``(method, path_format)`` may answer anonymous callers."""
    return (
        (method, path_format) in PUBLIC_HTTP_ROUTES
        or (method, path_format) in PUBLIC_DOCS_ROUTES
    )


def is_public_ws_route(method: str, path_format: str) -> bool:
    """Whether ``(method, path_format)`` may complete an anonymous WS handshake.

    ``method`` is always ``"WS"`` for WebSocket routes; it is accepted so HTTP
    and WS lookups share one shape at the call site.
    """
    return (method, path_format) in PUBLIC_WS_ROUTES
