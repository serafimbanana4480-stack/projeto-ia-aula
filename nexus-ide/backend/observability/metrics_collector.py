"""Real-time metrics collector for NEXUS IDE dashboard.

Collects system and application metrics:
- Token throughput from Ollama
- Active sessions from ContextStore
- System resources (CPU, RAM, Disk)
- Request latency
- Error rates
"""

from __future__ import annotations

import asyncio
import logging
import time
from collections import defaultdict
from dataclasses import dataclass

import psutil

logger = logging.getLogger(__name__)


@dataclass
class MetricsSnapshot:
    """Snapshot of current system metrics."""

    tokens_per_second: float
    active_model: str
    active_sessions: int
    queue_depth: int
    ram_used_bytes: float
    ram_total_bytes: float
    ram_percent: float
    cpu_percent: float
    disk_used_bytes: float
    disk_total_bytes: float
    disk_percent: float
    uptime_seconds: float
    requests_total: int
    requests_successful: int
    requests_failed: int
    avg_latency_ms: float
    timestamp: float


class MetricsCollector:
    """Collects and aggregates metrics from various sources."""

    def __init__(self):
        self._start_time = time.time()
        self._token_counter = defaultdict(int)
        self._request_counter = defaultdict(int)
        self._latency_samples: list[float] = []
        self._lock = asyncio.Lock()
        # Rolling window for tokens/s calculation (last 60s)
        self._token_events: list[tuple[float, int]] = []  # (timestamp, count)

    async def record_token(self, model: str, count: int) -> None:
        """Record tokens generated by a model."""
        async with self._lock:
            self._token_counter[model] += count
            now = time.time()
            self._token_events.append((now, count))
            # Prune events older than 120s (keep buffer)
            cutoff = now - 120
            self._token_events = [(t, c) for t, c in self._token_events if t > cutoff]

    async def record_token(self, model: str, count: int) -> None:
        """Record tokens generated by a model."""
        async with self._lock:
            self._token_counter[model] += count

    async def record_request(self, success: bool, latency_ms: float) -> None:
        """Record a request with success status and latency."""
        async with self._lock:
            self._request_counter["total"] += 1
            if success:
                self._request_counter["successful"] += 1
            else:
                self._request_counter["failed"] += 1
            self._latency_samples.append(latency_ms)
            # Keep only last 1000 samples to avoid memory bloat
            if len(self._latency_samples) > 1000:
                self._latency_samples = self._latency_samples[-1000:]

    async def get_snapshot(self, active_sessions: int = 0, queue_depth: int = 0) -> MetricsSnapshot:
        """Get current metrics snapshot."""
        async with self._lock:
            # Calculate tokens per second using rolling 60s window
            now = time.time()
            window_seconds = 60.0
            cutoff = now - window_seconds
            recent_events = [(t, c) for t, c in self._token_events if t > cutoff]
            if recent_events:
                tokens_in_window = sum(c for _, c in recent_events)
                oldest = recent_events[0][0]
                elapsed = max(now - oldest, 1.0)
                tokens_per_second = tokens_in_window / elapsed
            else:
                tokens_per_second = 0.0

            # Get active model (most used)
            active_model = (
                max(self._token_counter.keys(), key=lambda k: self._token_counter[k])
                if self._token_counter
                else "none"
            )

            # System metrics
            ram = psutil.virtual_memory()
            cpu = psutil.cpu_percent(interval=None)
            disk = psutil.disk_usage("/")
            uptime = now - self._start_time

            # Request metrics
            total_requests = self._request_counter.get("total", 0)
            successful = self._request_counter.get("successful", 0)
            failed = self._request_counter.get("failed", 0)

            # Average latency
            avg_latency = (
                sum(self._latency_samples) / len(self._latency_samples)
                if self._latency_samples
                else 0.0
            )

            return MetricsSnapshot(
                tokens_per_second=tokens_per_second,
                active_model=active_model,
                active_sessions=active_sessions,
                queue_depth=queue_depth,
                ram_used_bytes=ram.used,
                ram_total_bytes=ram.total,
                ram_percent=ram.percent,
                cpu_percent=cpu,
                disk_used_bytes=disk.used,
                disk_total_bytes=disk.total,
                disk_percent=disk.percent,
                uptime_seconds=uptime,
                requests_total=total_requests,
                requests_successful=successful,
                requests_failed=failed,
                avg_latency_ms=avg_latency,
                timestamp=time.time(),
            )

    async def get_token_counts(self) -> dict[str, int]:
        """Get token counts per model."""
        async with self._lock:
            return dict(self._token_counter)

    async def reset_counters(self) -> None:
        """Reset all counters (useful for testing or periodic reset)."""
        async with self._lock:
            self._token_counter.clear()
            self._request_counter.clear()
            self._latency_samples.clear()
            self._start_time = time.time()


# Global singleton
_collector: MetricsCollector | None = None


def get_metrics_collector() -> MetricsCollector:
    """Get or create the global metrics collector singleton."""
    global _collector
    if _collector is None:
        _collector = MetricsCollector()
    return _collector
