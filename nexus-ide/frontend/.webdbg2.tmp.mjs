import { chromium } from "playwright";
const log = (...a) => console.log("[dbg2]", ...a);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
page.on("requestfailed", (r) => log("FAILED:", r.url(), "|", r.failure()?.errorText));
page.on("request", (r) => { if (!r.url().includes("localhost:3000")) log("REQ:", r.method(), r.url()); });
page.on("response", (r) => { if (!r.url().includes("localhost:3000")) log("RES:", r.status(), r.url()); });
await page.goto("http://localhost:3000/login", { waitUntil: "networkidle", timeout: 120_000 });
await page.waitForTimeout(1500);
await page.fill("#email", "admin@nexus-ide.com");
await page.fill("#password", "admin123");
await page.click('button[type="submit"]');
await page.waitForTimeout(6000);
log("url:", page.url());
const token = await page.evaluate(() => localStorage.getItem("nexus.access_token"));
log("token:", token ? "OK" : "NONE");
await browser.close();
